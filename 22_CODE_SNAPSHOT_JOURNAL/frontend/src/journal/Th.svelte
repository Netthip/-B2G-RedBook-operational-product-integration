<script lang="ts">
  // ข้อความไทยที่ห้ามตัดกลางคำบางคำ — เบราว์เซอร์ตัดบรรทัดภาษาไทยด้วยพจนานุกรมของตัวเอง บางคำจึงถูกหั่น (งบ|ประมาณ · ต่าง|กัน · ความถูก|ต้อง)
  // คำในรายการจะขึ้นบรรทัดใหม่ไปทั้งคำ · ข้อความเดิมไม่เปลี่ยนแม้แต่ตัวเดียว
  let { s }: { s: string } = $props();
  const KEEP = /(สำนักงบประมาณ|งบประมาณ|ความถูกต้อง|หน้าหลักฐาน|หลักฐาน|ต่างกัน|ขั้นถัดไป|หน่วยงาน|ผู้ตัดสิน|ผู้ตรวจ|พ\.ร\.บ\.)/;
  const parts = $derived(s.split(KEEP));
</script>

