# -*- coding: utf-8 -*-
"""T1B — การอนุมานลำดับชั้นของแถว

ป้ายแถวเดียวกันปรากฏซ้ำได้ในชีตเดียวกัน — ตัวอย่างจริงใน
``XL_FY2569_draft-bill_21011_HSRI.xlsx`` ชีต ``Sheet5``
ข้อความ ``' เงินงบประมาณ'`` อยู่ทั้งแถว 10 (ใต้หัวข้อ ``1.``) และแถว 15 (ใต้หัวข้อ ``2.``)
โดยมีค่าต่างกัน (38.1527 กับ 15.1185)

⇒ ``row_label`` อย่างเดียว **ไม่ unique** ต้องมี ``hierarchy_path`` ประกอบเสมอ
"""
from __future__ import annotations

from .normalize import normalize_label, split_leading_number, strip_bullet


def parse_hierarchy(raw_labels: list[object]) -> list[tuple[str, ...]]:
    """อนุมานลำดับชั้นจากลำดับป้ายแถวทั้งชีต

    กติกา (มาจากรูปแบบที่พบจริง ไม่ใช่การเดา):

    1. แถวที่ **ขึ้นต้นด้วยเลข** (``1.`` ``2.1``) เป็นหัวข้อ — ``path = (เลข,)``
       และกลายเป็นหัวข้อปัจจุบันของแถวถัด ๆ ไป
    2. แถวที่อยู่ **ก่อนหัวข้อแรก** เป็นระดับบนสุดเสมอ — ``path = ()``
       กติกาข้อนี้จำเป็นเพราะไฟล์จริงมีช่องว่างนำหน้าเพิ่มเข้ามาโดยไม่ได้แปลว่าเป็นลูก
       (``'รวมเงินนอกงบประมาณ'`` ในปี 2569 กลายเป็น ``' รวมเงินนอกงบประมาณ'`` ในปี 2570)
    3. แถว **ทุกแถว** หลังหัวข้อแรกที่ไม่ได้ขึ้นต้นด้วยเลข เป็นลูกของหัวข้อปัจจุบัน
       — ``path = (เลขหัวข้อ, ป้ายที่ตัดเครื่องหมายแล้ว)``

    คืนรายการ ``path`` ยาวเท่ากับ ``raw_labels``

    🔴 **ห้ามใช้การย่อหน้าเป็นเงื่อนไขของความเป็นลูก** — พิสูจน์แล้วจากไฟล์จริง

    * แฟ้ม **ระดับหน่วยงาน** ย่อหน้าแถวลูก: ``' เงินงบประมาณ'``
    * แฟ้ม **ระดับกระทรวง** *ไม่* ย่อหน้า: ``'เงินงบประมาณ'`` (``ข้อ 5`` แถว 11 และ 16)

    ถ้าใช้การย่อหน้าเป็นเงื่อนไข แถวลูกของแฟ้มกระทรวงจะได้ ``path = ()`` ทั้งหมด
    ⇒ ``'เงินงบประมาณ'`` ใต้หัวข้อ ``1.`` และใต้หัวข้อ ``2.`` จะมีคีย์เดียวกัน
    (พบจริง **100 collision** ใน key stability audit)

    **ข้อจำกัดที่ทราบ:** รองรับลำดับชั้นสองระดับ (หัวข้อ → ลูก) เท่านั้น
    ยังไม่รองรับหัวข้อย่อยซ้อนหลายชั้น — ดูรายการค้างใน handoff
    """
    out: list[tuple[str, ...]] = []
    current_parent: str | None = None

    for raw in raw_labels:
        text = normalize_label(raw)
        if not text:
            out.append(())
            continue

        number, _rest = split_leading_number(raw)
        if number is not None:
            current_parent = number
            out.append((number,))
            continue

        if current_parent is None:
            # กติกาข้อ 2 — ก่อนหัวข้อแรก ย่อหน้าไม่ได้แปลว่าเป็นลูก
            out.append(())
            continue

        # หลังหัวข้อแรกแล้ว แถวที่ไม่ได้ขึ้นต้นด้วยเลขคือลูกของหัวข้อปัจจุบันเสมอ
        out.append((current_parent, strip_bullet(raw)))

    return out
